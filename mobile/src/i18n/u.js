/**
 * Localized text (fallback to English only).
 */
export const t = (lang, key, englishFallback = "") => {
  const L = PACKS[lang] || PACKS.en;
  return L[key] || englishFallback || PACKS.en[key] || "";
};

/**
 * Bilingual text for non-English languages only.
 * - If lang === 'en' -> English only
 * - If translation missing -> English only
 * - Otherwise -> "<localized> / <English>"
 */
export const tb = (lang, key, englishFallback = "") => {
  if (lang === "en") return t(lang, key, englishFallback);
  const L = PACKS[lang];
  const local = L && L[key];
  const eng = PACKS.en[key] || englishFallback;
  return local ? `${local} / ${eng}` : eng;
};
